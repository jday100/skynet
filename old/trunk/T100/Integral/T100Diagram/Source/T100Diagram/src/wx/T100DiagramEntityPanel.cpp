T100VOID T100DiagramEntityPanel::Clear()
{
    m_listView->Select(m_index, T100FALSE);
}

T100VOID T100DiagramEntityPanel::OnListViewItemSelect(wxListEvent& event)
{
    T100INT     index       = event.GetIndex();

    if(index < 0){
        return;
    }
    m_index     = index;

    T100UINT    value       = m_listView->GetItemData(index);

    T100DiagramInvoking::OnItemSelect(value);
}
