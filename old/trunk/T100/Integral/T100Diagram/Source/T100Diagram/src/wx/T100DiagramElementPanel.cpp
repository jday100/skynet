T100VOID T100DiagramElementPanel::uninit()
{

}

T100VOID T100DiagramElementPanel::Clear()
{
    m_listView->Select(m_index, T100FALSE);
}

T100VOID T100DiagramElementPanel::OnListViewItemSelect(wxListEvent& event)
{
    T100INT     index       = event.GetIndex();

    if(index < 0){
        return;
    }
    m_index     = index;

    T100UINT    value       = m_listView->GetItemData(index);

    T100DiagramInvoking::OnTieSelect(value);
}
