void T1003DEditorEntityPanel::OnSelected(wxListEvent& event)
{
    T100INT     value;

    m_item  = event.GetIndex();
    value   = event.GetData();

    SetCursor(*wxCROSS_CURSOR);

    T1003DEditorCallback::Update(value);
}

void T1003DEditorEntityPanel::OnMouseRightDown(wxMouseEvent& event)
{

}

T100VOID T1003DEditorEntityPanel::Clear()
{
    m_listCtrl->SetItemState(m_item, 0, wxLIST_STATE_SELECTED);
    SetCursor(wxNullCursor);
}
